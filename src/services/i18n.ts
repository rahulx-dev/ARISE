interface LanguageStore {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => Promise<void>;
  loadLanguage: () => Promise<void>;
  t: (key: string) => string;
}

export const useLanguageStore = create<LanguageStore>((set, get) => ({
  language: 'en-US', // Default to English
  loadLanguage: async () => {
    try {
      const records = await db.select().from(settings).limit(1);
      if (records.length > 0 && (records[0] as any).language) {
        set({ language: (records[0] as any).language as LanguageCode });
      }
    } catch {
      // Fallback
    }
  },
  setLanguage: async (lang: LanguageCode) => {
    set({ language: lang });
    try {
      const records = await db.select().from(settings).limit(1);
      if (records.length > 0) {
        await db.update(settings).set({ language: lang } as any);
      }
    } catch {
      // Fallback
    }
  },
  t: (key: string) => {
    const lang = get().language;
    const baseCode = lang.split('-')[0];
    const dict = TRANSLATIONS[lang] || TRANSLATIONS[baseCode] || TRANSLATIONS.en;
    return dict?.[key] || TRANSLATIONS.en[key] || key;
  },
}));

// Auto-initialize on app load
useLanguageStore.getState().loadLanguage().catch(() => {});
